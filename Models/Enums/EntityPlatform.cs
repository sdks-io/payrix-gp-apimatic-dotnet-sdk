using System;
using System.Text.Json.Serialization;
using Payrix.Core.Enum;

namespace Payrix.Models.Enums;

[JsonConverter(typeof(StringEnumConverter<EntityPlatform>))]
public sealed record EntityPlatform : OpenStringEnum<EntityPlatform>
{
    private EntityPlatform(string value) : base(value)
    {
    }

    public static readonly EntityPlatform Apple = new("APPLE");

    public static readonly EntityPlatform Elavon = new("ELAVON");

    public static readonly EntityPlatform Firstdata = new("FIRSTDATA");

    public static readonly EntityPlatform Google = new("GOOGLE");

    public static readonly EntityPlatform Vantiv = new("VANTIV");

    public static readonly EntityPlatform Vcore = new("VCORE");

    public static readonly EntityPlatform Wellsach = new("WELLSACH");

    public static readonly EntityPlatform Wellsfargo = new("WELLSFARGO");

    public static readonly EntityPlatform Wfsingle = new("WFSINGLE");

    public static readonly EntityPlatform Worldpay = new("WORLDPAY");

    public static readonly EntityPlatform Tdbankca = new("TDBANKCA");

    public TResult Match<TResult>(Func<TResult> onApple,
        Func<TResult> onElavon,
        Func<TResult> onFirstdata,
        Func<TResult> onGoogle,
        Func<TResult> onVantiv,
        Func<TResult> onVcore,
        Func<TResult> onWellsach,
        Func<TResult> onWellsfargo,
        Func<TResult> onWfsingle,
        Func<TResult> onWorldpay,
        Func<TResult> onTdbankca,
        Func<string, TResult> otherwise) =>
        this switch
        {
            _ when this == Apple => onApple(),
            _ when this == Elavon => onElavon(),
            _ when this == Firstdata => onFirstdata(),
            _ when this == Google => onGoogle(),
            _ when this == Vantiv => onVantiv(),
            _ when this == Vcore => onVcore(),
            _ when this == Wellsach => onWellsach(),
            _ when this == Wellsfargo => onWellsfargo(),
            _ when this == Wfsingle => onWfsingle(),
            _ when this == Worldpay => onWorldpay(),
            _ when this == Tdbankca => onTdbankca(),
            _ => otherwise(Value)
        };

    public void Match(Action onApple,
        Action onElavon,
        Action onFirstdata,
        Action onGoogle,
        Action onVantiv,
        Action onVcore,
        Action onWellsach,
        Action onWellsfargo,
        Action onWfsingle,
        Action onWorldpay,
        Action onTdbankca,
        Action<string> otherwise)
    {
        if (this == Apple) onApple();
        else if (this == Elavon) onElavon();
        else if (this == Firstdata) onFirstdata();
        else if (this == Google) onGoogle();
        else if (this == Vantiv) onVantiv();
        else if (this == Vcore) onVcore();
        else if (this == Wellsach) onWellsach();
        else if (this == Wellsfargo) onWellsfargo();
        else if (this == Wfsingle) onWfsingle();
        else if (this == Worldpay) onWorldpay();
        else if (this == Tdbankca) onTdbankca();
        else otherwise(Value);
    }
}
